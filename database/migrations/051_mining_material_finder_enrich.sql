-- 1) Tabla de firmas multiples por (material, metodo)
CREATE TABLE IF NOT EXISTS mining_material_signature_variants (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  material_name     TEXT NOT NULL,
  method            TEXT NOT NULL CHECK (method IN ('Ship','ROC','Hand')),
  radar_signature   INTEGER NOT NULL,
  sort_order        INTEGER NOT NULL DEFAULT 0,
  source            TEXT,
  dataset_version   TEXT NOT NULL,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),

  UNIQUE (material_name, method, radar_signature, dataset_version)
);

CREATE INDEX IF NOT EXISTS idx_mmsv_material ON mining_material_signature_variants(material_name);
CREATE INDEX IF NOT EXISTS idx_mmsv_method   ON mining_material_signature_variants(method);
CREATE INDEX IF NOT EXISTS idx_mmsv_sig      ON mining_material_signature_variants(radar_signature);

ALTER TABLE mining_material_signature_variants ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname='mmsv_public_read') THEN
    CREATE POLICY mmsv_public_read ON mining_material_signature_variants FOR SELECT USING (true);
  END IF;
END $$;

